import { start, readFile, writeFile } from './lib.mjs';
import { tmpdir } from 'node:os';
const SC = process.argv[2] || tmpdir();
const { browser, page, errors } = await start();
let pass = 0, fail = 0;
const ok = (c, m, x = '') => { c ? pass++ : fail++; console.log((c ? '  ok   ' : '  FAIL ') + m + (c ? '' : ' ' + x)); };
const settle = ms => page.waitForTimeout(ms ?? 700);

console.log('# conflict backup');
await page.evaluate(() => { const v = hermes.vault; const p = v.pages.get('Reading List.md'); p.nodes[0].text = 'Books (edited locally)'; v.touch(p); });
await writeFile(page, 'Reading List.md', '- Totally different external content\n');
await settle(1500);
const files = await page.evaluate(async () => { const root = await navigator.storage.getDirectory(); const d = await (await root.getDirectoryHandle('hermes-demo')).getDirectoryHandle('.hermes').then(h => h.getDirectoryHandle('backups')).catch(() => null); if (!d) return []; const out = []; for await (const [n] of d.entries()) out.push(n); return out; });
ok(files.some(f => f.startsWith('Reading List.md.')), 'external version is backed up before our write replaces it', files.join());
ok((await readFile(page, 'Reading List.md')).includes('Books (edited locally)'), 'local edit is what ends up on disk');

console.log('# new field, rename field, record modal');
await page.click('.side-item[data-db="book"]');
await page.waitForSelector('table.grid');
ok((await page.$$eval('tr.rec', e => e.length)) === 5, 'book table shows 5 records');
await page.click('th.addcol button');
await page.fill('.dialog input', 'genre');
await page.keyboard.press('Enter');
await settle(400);
await page.locator('tr.rec', { hasText: 'Deep Work' }).locator('td[data-key="genre"]').click();
await page.keyboard.type('Productivity');
await page.keyboard.press('Enter');
await settle(900);
let md = await readFile(page, 'Reading List.md');
ok(/Deep Work #book\n(\s+- .*\n)*\s+- genre:: Productivity/.test(md) , 'new field value written as child bullet', md);
await page.locator('th[data-key="genre"] .th-btn').click();
await page.click('.menu-item:has-text("Rename field")');
await page.fill('.dialog input', 'category');
await page.keyboard.press('Enter');
await settle(900);
md = await readFile(page, 'Reading List.md');
ok(/category:: Productivity/.test(md) && !/genre::/.test(md), 'rename field rewrites every record');
await page.locator('tr.rec', { hasText: 'Deep Work' }).hover();
await page.locator('tr.rec', { hasText: 'Deep Work' }).locator('.row-open').click();
await page.waitForSelector('.rec-modal');
await page.screenshot({ path: SC + '/15-record-modal.png' });
await page.fill('.rec-modal .rec-val input[type="text"] >> nth=0', 'Cal Newport Jr');
await page.keyboard.press('Enter');
await page.click('.rec-modal .icon-btn');
await settle(900);
md = await readFile(page, 'Reading List.md');
ok(/author:: Cal Newport Jr/.test(md), 'record modal edits write through');

console.log('# new records + views');
await page.click('.split-main');
await settle(600);
await page.keyboard.type('Atomic Habits');
await page.keyboard.press('Enter');
await settle(900);
const inbox = await readFile(page, 'Inbox.md');
ok(/Atomic Habits #book/.test(inbox), '"New" adds a tagged bullet to Inbox.md', inbox);
await page.click('.split-caret'); await page.click('.menu-item:has-text("New page")');
await settle(900);
const pg = await page.evaluate(async () => { const root = await navigator.storage.getDirectory(); const d = await (await root.getDirectoryHandle('hermes-demo')).getDirectoryHandle('book'); const out = []; for await (const [n] of d.entries()) out.push(n); return out; });
ok(pg.includes('Untitled.md'), 'New page record creates book/Untitled.md with frontmatter tag');
const nm = await readFile(page, 'book/Untitled.md');
ok(/^---\ntags:\n  - book\n---/.test(nm), 'page record frontmatter', nm);
await page.click('.tab.add'); await page.click('.menu-item:has-text("Table")');
await settle(400);
ok((await page.$$('.tab:not(.add)')).length === 2, 'second view added as a tab');
await page.reload();
await page.waitForSelector('.tab');
ok((await page.$$('.tab:not(.add)')).length === 2, 'views persist in .hermes/config.json after reload');
const cfg = JSON.parse(await readFile(page, '.hermes/config.json'));
ok(cfg.views.filter(v => v.tag === 'book').length === 2 && cfg.schema.book.fields.some(f => f.name === 'category'), 'config has views + schema');

console.log('# renaming a page record from the table');
await page.click('.side-item[data-db="project"]');
await page.waitForSelector('table.grid');
await page.locator('tr.rec', { hasText: 'Q4 Planning' }).locator('td[data-key="@title"]').click();
await page.keyboard.press('Control+a');
await page.keyboard.type('Q4 Roadmap');
await page.keyboard.press('Enter');
await settle(1200);
const projFiles = await page.evaluate(async () => { const root = await navigator.storage.getDirectory(); const d = await (await root.getDirectoryHandle('hermes-demo')).getDirectoryHandle('Projects'); const out = []; for await (const [n] of d.entries()) out.push(n); return out; });
ok(projFiles.includes('Q4 Roadmap.md') && !projFiles.includes('Q4 Planning.md'), 'renaming a page record renames its file', projFiles.join());
ok((await readFile(page, await page.evaluate(() => hermes.vault.dailyPath()))).includes('[[Q4 Roadmap]]'), 'links to the renamed page are rewritten');

console.log('# headings + slash');
await page.evaluate(() => hermes.go({ path: 'Reading List.md' }));
await page.waitForSelector('.row');
await page.click('.row .view >> nth=0', { position: { x: 5, y: 5 } });
await page.keyboard.press('Control+End');
await page.keyboard.press('Control+ArrowDown');
await page.evaluate(() => { const ta = document.activeElement; ta.setSelectionRange(ta.value.length, ta.value.length); });
await page.keyboard.press('Enter'); await page.keyboard.press('Shift+Tab');
await page.keyboard.type('## Section title');
await settle(900);
md = await readFile(page, 'Reading List.md');
ok(/^## Section title$/m.test(md), '"## " at top level converts to a markdown heading', md.slice(-200));
await page.keyboard.press('Enter');
await page.keyboard.type('/tod');
await page.waitForSelector('.suggest');
await page.keyboard.press('Enter');
await settle(300);
ok(/^\d{4}-\d{2}-\d{2}$/.test(await page.evaluate(() => document.activeElement.value)), 'slash command inserts today');

console.log('# empty vault');
await page.evaluate(async () => {
  const root = await navigator.storage.getDirectory();
  await root.getDirectoryHandle('empty-vault', { create: true });
  window.showDirectoryPicker = async () => root.getDirectoryHandle('empty-vault');
  await hermes.switchVault();
});
await page.waitForSelector('text=Open a folder');
await page.click('text=Open a folder');
await page.waitForSelector('.db');
ok((await page.textContent('.empty-row')).includes('no notes yet'), 'empty folder shows a helpful state');
await page.screenshot({ path: SC + '/16-empty.png' });
await page.keyboard.press('Alt+n');
await page.fill('.dialog input', 'Projects/First Note');
await page.keyboard.press('Enter');
await page.waitForSelector('.page-title');
ok((await page.inputValue('.page-title')) === 'First Note', 'Alt+N creates Folder/Name pages');

console.log(`\n${pass} passed, ${fail} failed`);
console.log('ERRORS:', errors.join('\n') || 'none');
await browser.close();
